//! The app's texts (ADR-0096): reads every part's Fluent files and writes, for each part, one
//! Rust function per message of the reference language (German), so a missing or misspelt
//! message fails the build. A message without variables gives `fn id() -> &'static str`,
//! one with variables `fn id(a: impl Arg, …) -> String`; the variables come in the order a
//! comment line `Variables: $a, $b` names them, else in the order they first appear.
//! Every file of every language is embedded, for the app to read at run time.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use fluent_syntax::ast;

/// The language every other one is checked against, and falls back to.
const REFERENCE: &str = "de";

pub fn texts(app: &Path, out: &Path) {
    let locales = app.join("locales");
    println!("cargo:rerun-if-changed={}", locales.display());
    // language -> part -> file
    let mut files: BTreeMap<String, BTreeMap<String, std::path::PathBuf>> = BTreeMap::new();
    for language in read_dir(&locales) {
        println!("cargo:rerun-if-changed={}", language.display());
        let name = file_name(&language);
        for file in read_dir(&language) {
            if file.extension().is_some_and(|e| e == "ftl") {
                println!("cargo:rerun-if-changed={}", file.display());
                let part = file
                    .file_stem()
                    .and_then(|s| s.to_str())
                    .expect("a part's name")
                    .to_owned();
                files.entry(name.clone()).or_default().insert(part, file);
            }
        }
    }
    let reference = files
        .get(REFERENCE)
        .unwrap_or_else(|| panic!("no texts in {}/{REFERENCE}", locales.display()));

    // Every file, embedded: (language, part, source).
    let mut sources = String::from("/// Every Fluent file: (language, part, source).\n");
    sources.push_str("pub const SOURCES: &[(&str, &str, &str)] = &[\n");
    for (language, parts) in &files {
        for (part, file) in parts {
            let source = std::fs::read_to_string(file)
                .unwrap_or_else(|e| panic!("read {}: {e}", file.display()));
            // Every file must parse; the test compares the languages.
            if let Err((_, errors)) = fluent_syntax::parser::parse(source.as_str()) {
                panic!("{}: {errors:?}", file.display());
            }
            writeln!(
                sources,
                "    ({language:?}, {part:?}, include_str!({:?})),",
                file.display().to_string()
            )
            .expect("write");
        }
    }
    sources.push_str("];\n");
    std::fs::write(out.join("fluent_sources.rs"), sources).expect("write the Fluent sources");

    // One module of functions per part, from the reference language.
    for (part, file) in reference {
        let source = std::fs::read_to_string(file).expect("read");
        let resource = fluent_syntax::parser::parse(source.as_str()).expect("parsed above");
        let mut code = format!(
            "// Generated by build/fluent.rs from {}: one function per message.\n",
            file.display()
        );
        // Messages other messages refer to may have no caller in the code.
        let mut referenced = std::collections::BTreeSet::new();
        for entry in &resource.body {
            if let ast::Entry::Message(m) = entry
                && let Some(p) = &m.value
            {
                pattern_references(p, &mut referenced);
            }
        }
        let mut seen = std::collections::BTreeSet::new();
        for entry in &resource.body {
            let ast::Entry::Message(message) = entry else {
                continue;
            };
            let id = message.id.name;
            assert!(seen.insert(id), "{}: message {id} twice", file.display());
            let pattern = message
                .value
                .as_ref()
                .unwrap_or_else(|| panic!("{}: message {id} has no value", file.display()));
            let mut found = Vec::new();
            pattern_variables(pattern, &mut found);
            let variables = ordered(message.comment.as_ref(), &found)
                .unwrap_or_else(|e| panic!("{}: message {id}: {e}", file.display()));
            let function = id.replace('-', "_");
            writeln!(code, "/// {}", doc(pattern)).expect("write");
            if referenced.contains(id) {
                code.push_str("#[allow(dead_code)]\n");
            }
            if variables.is_empty() {
                writeln!(
                    code,
                    "pub fn {function}() -> &'static str {{ crate::i18n::message({part:?}, {id:?}) }}"
                )
                .expect("write");
            } else {
                let params: Vec<String> = variables
                    .iter()
                    .map(|v| format!("{}: impl crate::i18n::Arg", v.replace('-', "_")))
                    .collect();
                let sets: String = variables
                    .iter()
                    .map(|v| {
                        format!(
                            "args.set({v:?}, crate::i18n::Arg::value({}));",
                            v.replace('-', "_")
                        )
                    })
                    .collect();
                writeln!(
                    code,
                    "pub fn {function}({}) -> String {{ let mut args = crate::i18n::Args::new(); {sets} crate::i18n::format({part:?}, {id:?}, &args) }}",
                    params.join(", ")
                )
                .expect("write");
            }
        }
        std::fs::write(out.join(format!("text_{part}.rs")), code)
            .unwrap_or_else(|e| panic!("write the texts of {part}: {e}"));
    }
}

fn read_dir(dir: &Path) -> Vec<std::path::PathBuf> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .map(|e| e.expect("a directory entry").path())
        .collect();
    entries.sort();
    entries
}

fn file_name(path: &Path) -> String {
    path.file_name()
        .and_then(|n| n.to_str())
        .expect("a name")
        .to_owned()
}

/// The variables in the order the comment names them (`Variables: $a, $b`), which must be
/// exactly those used; else in the order they first appear.
fn ordered(comment: Option<&ast::Comment<&str>>, found: &[String]) -> Result<Vec<String>, String> {
    let named = comment.and_then(|c| {
        c.content
            .iter()
            .find_map(|line| line.trim().strip_prefix("Variables:"))
            .map(|list| {
                list.split(',')
                    .map(|v| v.trim().trim_start_matches('$').to_owned())
                    .filter(|v| !v.is_empty())
                    .collect::<Vec<_>>()
            })
    });
    match named {
        None => Ok(found.to_vec()),
        Some(named) => {
            let mut a = named.clone();
            let mut b = found.to_vec();
            a.sort();
            b.sort();
            if a == b {
                Ok(named)
            } else {
                Err(format!(
                    "the comment names {named:?}, the message uses {found:?}"
                ))
            }
        }
    }
}

fn pattern_references(
    pattern: &ast::Pattern<&str>,
    found: &mut std::collections::BTreeSet<String>,
) {
    for element in &pattern.elements {
        if let ast::PatternElement::Placeable { expression } = element {
            match expression {
                ast::Expression::Inline(ast::InlineExpression::MessageReference { id, .. }) => {
                    found.insert(id.name.to_owned());
                }
                ast::Expression::Select { variants, .. } => {
                    for v in variants {
                        pattern_references(&v.value, found);
                    }
                }
                _ => {}
            }
        }
    }
}

fn pattern_variables(pattern: &ast::Pattern<&str>, found: &mut Vec<String>) {
    for element in &pattern.elements {
        if let ast::PatternElement::Placeable { expression } = element {
            expression_variables(expression, found);
        }
    }
}

fn expression_variables(expression: &ast::Expression<&str>, found: &mut Vec<String>) {
    match expression {
        ast::Expression::Inline(inline) => inline_variables(inline, found),
        ast::Expression::Select { selector, variants } => {
            inline_variables(selector, found);
            for variant in variants {
                pattern_variables(&variant.value, found);
            }
        }
    }
}

fn inline_variables(inline: &ast::InlineExpression<&str>, found: &mut Vec<String>) {
    match inline {
        ast::InlineExpression::VariableReference { id } => {
            if !found.iter().any(|f| f == id.name) {
                found.push(id.name.to_owned());
            }
        }
        ast::InlineExpression::FunctionReference { arguments, .. } => {
            for argument in &arguments.positional {
                inline_variables(argument, found);
            }
            for named in &arguments.named {
                inline_variables(&named.value, found);
            }
        }
        ast::InlineExpression::Placeable { expression } => expression_variables(expression, found),
        _ => {}
    }
}

/// The message's text for the generated function's documentation, on one line.
fn doc(pattern: &ast::Pattern<&str>) -> String {
    let mut text = String::new();
    for element in &pattern.elements {
        match element {
            ast::PatternElement::TextElement { value } => text.push_str(value),
            ast::PatternElement::Placeable { expression } => text.push_str(&placeable(expression)),
        }
    }
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn placeable(expression: &ast::Expression<&str>) -> String {
    match expression {
        ast::Expression::Inline(ast::InlineExpression::VariableReference { id }) => {
            format!("{{ ${} }}", id.name)
        }
        ast::Expression::Inline(ast::InlineExpression::StringLiteral { value }) => {
            (*value).to_owned()
        }
        ast::Expression::Select { variants, .. } => {
            let default = variants.iter().find(|v| v.default).or(variants.first());
            default.map(|v| doc(&v.value)).unwrap_or_default()
        }
        _ => "{ … }".to_owned(),
    }
}
