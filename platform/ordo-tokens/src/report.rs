//! Human-readable contrast report (Markdown), as input for the accessibility
//! conformance report (requirements A11Y-11).

use std::fmt::Write;

use crate::color::format_ratio;
use crate::design::{CheckReport, ThemeReport};

/// Renders the report for all themes.
pub fn markdown(report: &CheckReport) -> String {
    let mut out = String::from(
        "# Colour contrast report\n\n\
         Generated by `ordo-tokens` from `design/`. Thresholds: WCAG 2.2 success criterion \
         1.4.3 (text, 4.5:1) and 1.4.11 (non-text, 3:1). Ratios are rounded down.\n\n",
    );
    let total: usize = report.themes.iter().map(|t| t.results.len()).sum();
    let failed: usize = report.themes.iter().map(|t| t.failures().count()).sum();
    writeln!(
        out,
        "**Result:** {} of {total} checks pass across {} themes.\n",
        total - failed,
        report.themes.len()
    )
    .ok();
    for theme in &report.themes {
        theme_section(&mut out, theme);
    }
    out
}

/// Renders the report for one theme.
pub fn theme_section(out: &mut String, theme: &ThemeReport) {
    writeln!(out, "## Theme: {}\n", theme.theme).ok();
    out.push_str("| Purpose | Foreground | Background | Ratio | Minimum | WCAG | Result |\n");
    out.push_str("|---|---|---|---|---|---|---|\n");
    for r in &theme.results {
        writeln!(
            out,
            "| {} | `{}` {} | `{}` {} | {} | {} | {} | {} |",
            r.pair.purpose,
            r.pair.fg,
            r.fg.to_hex(),
            r.pair.bg,
            r.bg.to_hex(),
            format_ratio(r.ratio),
            format_ratio(r.pair.min),
            r.pair.criterion,
            if r.passes() { "pass" } else { "**FAIL**" }
        )
        .ok();
    }
    out.push('\n');
}
