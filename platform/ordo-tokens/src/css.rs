//! CSS output.
//!
//! Base tokens and the default theme go into `:root`. Every other theme gets a
//! `:root[data-theme="…"]` block, and themes with a media query are also applied
//! automatically when the page doesn't choose a theme itself. Aliases become `var()`
//! references, so switching a theme only switches the semantic tokens.

use std::fmt::Write;

use crate::Error;
use crate::design::{DesignSystem, Resolver};
use crate::dtcg::{RawValue, Token, TokenType};
use crate::value::Value;

/// The CSS custom property name for a token path, e.g. `color.text.onFill` →
/// `--ordo-color-text-on-fill`.
pub fn var_name(prefix: &str, path: &str) -> String {
    let mut name = format!("--{prefix}");
    for segment in path.split('.') {
        name.push('-');
        for c in segment.chars() {
            if c.is_ascii_uppercase() {
                name.push('-');
                name.push(c.to_ascii_lowercase());
            } else {
                name.push(c);
            }
        }
    }
    name
}

/// Generates the complete style sheet.
// [impl->dsn~css-themes~1]
pub fn generate(system: &DesignSystem) -> Result<String, Error> {
    let prefix = &system.manifest.prefix;
    let (default_entry, default_tokens) = system.theme(&system.manifest.default_theme)?;
    let resolver = Resolver::new(system.base.iter().chain(default_tokens));

    let mut css = String::from(
        "/* Generated by ordo-tokens from the ORDO design tokens (design/). Do not edit. */\n\n",
    );
    block(
        &mut css,
        "",
        ":root",
        default_entry.color_scheme.as_deref(),
        system.base.iter().chain(default_tokens),
        prefix,
        &resolver,
    )?;

    for (entry, tokens) in &system.themes {
        if entry.name == default_entry.name {
            continue;
        }
        let resolver = Resolver::new(system.base.iter().chain(tokens));
        let selector = format!(":root[data-theme=\"{}\"]", entry.name);
        block(
            &mut css,
            "",
            &selector,
            entry.color_scheme.as_deref(),
            tokens,
            prefix,
            &resolver,
        )?;
    }

    for (entry, tokens) in &system.themes {
        let Some(media) = &entry.media else { continue };
        let resolver = Resolver::new(system.base.iter().chain(tokens));
        writeln!(css, "@media {media} {{").ok();
        block(
            &mut css,
            "  ",
            ":root:not([data-theme])",
            entry.color_scheme.as_deref(),
            tokens,
            prefix,
            &resolver,
        )?;
        css.push_str("}\n\n");
    }

    // Reduced motion: every literal duration becomes 0 ms; aliases follow.
    let durations: Vec<&Token> = system
        .base
        .iter()
        .filter(|t| t.ty == Some(TokenType::Duration) && matches!(t.value, RawValue::Literal(_)))
        .collect();
    if !durations.is_empty() {
        css.push_str("@media (prefers-reduced-motion: reduce) {\n  :root, :root[data-theme] {\n");
        for token in durations {
            writeln!(css, "    {}: 0ms;", var_name(prefix, &token.path)).ok();
        }
        css.push_str("  }\n}\n");
    }
    Ok(css)
}

#[allow(clippy::too_many_arguments)]
fn block<'a>(
    css: &mut String,
    indent: &str,
    selector: &str,
    color_scheme: Option<&str>,
    tokens: impl IntoIterator<Item = &'a Token>,
    prefix: &str,
    resolver: &Resolver<'_>,
) -> Result<(), Error> {
    writeln!(css, "{indent}{selector} {{").ok();
    if let Some(scheme) = color_scheme {
        writeln!(css, "{indent}  color-scheme: {scheme};").ok();
    }
    for token in tokens {
        let value = match &token.value {
            RawValue::Alias(target) => format!("var({})", var_name(prefix, target)),
            RawValue::Literal(_) => {
                let (_, value): (TokenType, Value) = resolver.resolve(&token.path)?;
                value.to_css()
            }
        };
        writeln!(css, "{indent}  {}: {value};", var_name(prefix, &token.path)).ok();
    }
    writeln!(css, "{indent}}}\n").ok();
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::var_name;

    #[test]
    fn names_are_kebab_case() {
        assert_eq!(
            var_name("ordo", "color.safety.triage.immediate.onFill"),
            "--ordo-color-safety-triage-immediate-on-fill"
        );
        assert_eq!(var_name("ordo", "space.4"), "--ordo-space-4");
    }
}
